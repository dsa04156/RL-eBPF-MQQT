#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
EDA analyzer for MQTT pub/sub latency logs.

Input  (subscriber side):
  - CSV lines like: "<ts>,latency_s,<value>"
    (no header; generated by subscriber containers)
  - Multiple files via glob, e.g. ~/mqtt-ebpf-edge/results/ours/subs/<RUN_ID>/*_lat.csv

Optional input (broker side, ours):
  - eBPF JSONL: eda_log.jsonl or eda_log_<RUN_ID>.jsonl
    Each line: {"ts": ..., "rtt_us":..., "retrans":..., "sndbuf":..., ...}

Output:
  - Console summary
  - CSV summary (--out), with aggregated metrics and per-host metrics if --per-host-out is given

Usage examples
--------------
# Single set (baseline only)
python3 analyze.py --mode single \
  --glob "$HOME/mqtt-ebpf-edge/results/baseline/subs/base_run1/*_lat.csv" \
  --out "$HOME/mqtt-ebpf-edge/results/baseline/summary_base_run1.csv"

# Compare baseline vs ours
python3 analyze.py --mode compare \
  --glob-base "$HOME/mqtt-ebpf-edge/results/baseline/subs/base_run1/*_lat.csv" \
  --glob-ours "$HOME/mqtt-ebpf-edge/results/ours/subs/ours_run1/*_lat.csv" \
  --out "$HOME/mqtt-ebpf-edge/results/compare_summary_run1.csv" \
  --eda-ours "$HOME/mqtt-ebpf-edge/results/ours/eda_log_ours_run1.jsonl"

# Filter out extreme latencies (e.g., > 10s) and save per-host table too
python3 analyze.py --mode single \
  --glob "$HOME/mqtt-ebpf-edge/results/ours/subs/ours_run1/*_lat.csv" \
  --lat-max 10.0 \
  --out "$HOME/mqtt-ebpf-edge/results/ours/summary_ours_run1.csv" \
  --per-host-out "$HOME/mqtt-ebpf-edge/results/ours/summary_ours_run1_per_host.csv"
"""

from __future__ import annotations
import argparse, json, math, re
from pathlib import Path
from typing import Dict, List, Tuple, Optional

import numpy as np
import pandas as pd
import os, glob


def parse_latency_file(path: Path) -> pd.DataFrame:
    """
    Parse a single *_lat.csv file which has lines:
      <ts_float>,latency_s,<latency_float>
    Robust to stray lines; returns DataFrame with columns:
      ['host','ts','lat_s']
    """
    host = path.stem.replace("_lat", "")
    ts_list: List[float] = []
    lat_list: List[float] = []

    with path.open("r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            # fast path: split by comma, expect 3 columns
            parts = line.strip().split(",")
            if len(parts) != 3:
                continue
            # parts[1] should be 'latency_s' (or tolerate any string containing 'lat')
            if "lat" not in parts[1]:
                continue
            try:
                ts = float(parts[0])
                val = float(parts[2])
            except ValueError:
                continue
            # If the second token implies milliseconds, convert to seconds
            if "ms" in parts[1]:
                val = val / 1000.0
            ts_list.append(ts)
            lat_list.append(val)

    if not ts_list:
        return pd.DataFrame(columns=["host", "ts", "lat_s"])

    df = pd.DataFrame({"host": host, "ts": ts_list, "lat_s": lat_list})
    return df


def load_glob(glob_pat: str) -> pd.DataFrame:
    # 절대경로/틸드(~) 포함 패턴도 안전하게 처리
    pat = os.path.expanduser(glob_pat)
    files = [Path(p) for p in sorted(glob.glob(pat))]
    dfs = []
    for p in files:
        try:
            df = parse_latency_file(p)
            if not df.empty:
                dfs.append(df)
        except Exception:
            continue
    if not dfs:
        return pd.DataFrame(columns=["host", "ts", "lat_s"])
    return pd.concat(dfs, ignore_index=True)



def summarize(df: pd.DataFrame, label: str = "") -> Tuple[pd.DataFrame, Dict[str, float]]:
    """
    Returns:
      - per_host: DataFrame with per-host stats
      - agg: dict with aggregated stats across all hosts
    """
    if df.empty:
        empty = {
            "label": label, "hosts": 0, "n": 0,
            "p50_ms": math.nan, "p90_ms": math.nan, "p95_ms": math.nan, "p99_ms": math.nan,
            "mean_ms": math.nan, "std_ms": math.nan, "min_ms": math.nan, "max_ms": math.nan,
            "throughput_msg_s": math.nan, "duration_s": math.nan,
        }
        return pd.DataFrame(columns=["host","n","p50_ms","p90_ms","p95_ms","p99_ms","mean_ms","std_ms","min_ms","max_ms","throughput_msg_s","duration_s"]), empty

    # Per-host stats
    rows = []
    for host, g in df.groupby("host", sort=False):
        if g.empty:
            continue
        lat_ms = g["lat_s"].to_numpy(dtype=float) * 1000.0
        # basic stats
        p50, p90, p95, p99 = np.quantile(lat_ms, [0.5, 0.9, 0.95, 0.99])
        mean = float(np.mean(lat_ms))
        std = float(np.std(lat_ms, ddof=1)) if len(lat_ms) > 1 else 0.0
        minv, maxv = float(np.min(lat_ms)), float(np.max(lat_ms))
        n = int(lat_ms.size)
        # throughput per host ~ N / (tmax - tmin)
        tmin, tmax = float(g["ts"].min()), float(g["ts"].max())
        dur = max(0.0, tmax - tmin)
        thr = (n / dur) if dur > 0 else float("nan")
        rows.append({
            "host": host, "n": n,
            "p50_ms": p50, "p90_ms": p90, "p95_ms": p95, "p99_ms": p99,
            "mean_ms": mean, "std_ms": std, "min_ms": minv, "max_ms": maxv,
            "throughput_msg_s": thr, "duration_s": dur,
        })
    per_host = pd.DataFrame(rows).sort_values("host").reset_index(drop=True)

    # Aggregated across all hosts (pooled latencies)
    lat_ms_all = (df["lat_s"].to_numpy(dtype=float) * 1000.0)
    total_n = int(lat_ms_all.size)
    p50, p90, p95, p99 = np.quantile(lat_ms_all, [0.5, 0.9, 0.95, 0.99])
    mean = float(np.mean(lat_ms_all))
    std = float(np.std(lat_ms_all, ddof=1)) if total_n > 1 else 0.0
    minv, maxv = float(np.min(lat_ms_all)), float(np.max(lat_ms_all))
    # Throughput aggregate: sum of per-host throughputs (better than using global min/max across hosts due to clock skew)
    thr_sum = per_host["throughput_msg_s"].replace([np.inf, -np.inf], np.nan).sum(skipna=True)
    # Duration (median across hosts for reference)
    duration_med = per_host["duration_s"].median() if not per_host.empty else float("nan")

    agg = {
        "label": label,
        "hosts": int(per_host.shape[0]),
        "n": total_n,
        "p50_ms": p50, "p90_ms": p90, "p95_ms": p95, "p99_ms": p99,
        "mean_ms": mean, "std_ms": std, "min_ms": minv, "max_ms": maxv,
        "throughput_msg_s": float(thr_sum),
        "duration_s": float(duration_med),
    }
    return per_host, agg


def clip_latencies(df: pd.DataFrame, lat_min: Optional[float], lat_max: Optional[float]) -> pd.DataFrame:
    """Filter by latency bounds in *seconds*."""
    if df.empty:
        return df
    out = df.copy()
    if lat_min is not None:
        out = out[out["lat_s"] >= lat_min]
    if lat_max is not None:
        out = out[out["lat_s"] <= lat_max]
    return out.reset_index(drop=True)


def load_eda_jsonl(path: Optional[str]) -> Dict[str, float]:
    """
    Summarize eBPF EDA JSONL; auto-detect keys.
    Supports:
      - New schema (current eda.py): rtt_ms, retrans_delta, sndbuf, rcvbuf, interval_s
      - Old schema: rtt_us, retrans, sndbuf, rcvbuf
    Returns mean/p95/max for rtt(ms), sndbuf, rcvbuf, and retrans_per_s when derivable.
    """
    if not path:
        return {}
    p = Path(path).expanduser()
    if not p.exists():
        return {}

    rtt_ms_vals, snd_vals, rcv_vals = [], [], []
    retrans_per_s_vals = []  # prefer Δ/interval; fallback to diffs if only 'retrans' exists
    last_retrans = None
    last_ts = None
    last_seen_interval = None

    try:
        with p.open("r", encoding="utf-8", errors="ignore") as f:
            for line in f:
                try:
                    o = json.loads(line)
                except Exception:
                    continue

                # RTT: prefer rtt_ms; else rtt_us → ms
                if "rtt_ms" in o and isinstance(o["rtt_ms"], (int, float)):
                    rtt_ms_vals.append(float(o["rtt_ms"]))
                elif "rtt_us" in o and isinstance(o["rtt_us"], (int, float)):
                    rtt_ms_vals.append(float(o["rtt_us"]) / 1000.0)

                # Buffers
                if "sndbuf" in o and isinstance(o["sndbuf"], (int, float)):
                    snd_vals.append(float(o["sndbuf"]))
                if "rcvbuf" in o and isinstance(o["rcvbuf"], (int, float)):
                    rcv_vals.append(float(o["rcvbuf"]))

                # Retrans per second:
                # 1) best: retrans_delta / interval_s
                if "retrans_delta" in o and isinstance(o["retrans_delta"], (int, float)):
                    interval = None
                    if "interval_s" in o and isinstance(o["interval_s"], (int, float)) and o["interval_s"] > 0:
                        interval = float(o["interval_s"])
                    elif last_seen_interval:  # reuse last seen positive interval
                        interval = last_seen_interval
                    if interval and interval > 0:
                        retrans_per_s_vals.append(float(o["retrans_delta"]) / interval)
                        last_seen_interval = interval
                        continue  # prefer delta-based path; skip fallback for this line

                # 2) fallback: cumulative 'retrans' diffs over Δt (if both present)
                if "retrans" in o and isinstance(o["retrans"], (int, float)):
                    cur_retrans = float(o["retrans"])
                    cur_ts = float(o.get("ts", 0.0))
                    if last_retrans is not None and last_ts is not None and cur_ts > last_ts:
                        diff = max(0.0, cur_retrans - last_retrans)
                        dt = cur_ts - last_ts
                        retrans_per_s_vals.append(diff / dt if dt > 0 else 0.0)
                    last_retrans, last_ts = cur_retrans, cur_ts
    except Exception:
        return {}

    def stats(arr):
        if not arr:
            return {}
        a = np.asarray(arr, dtype=float)
        return {
            "mean": float(np.mean(a)),
            "p95":  float(np.quantile(a, 0.95)),
            "max":  float(np.max(a)),
        }

    out = {}
    if rtt_ms_vals:  # ms
        s = stats(rtt_ms_vals)
        out["rtt_ms_mean"] = s["mean"]; out["rtt_ms_p95"] = s["p95"]; out["rtt_ms_max"] = s["max"]
    if snd_vals:
        s = stats(snd_vals)
        out["sndbuf_mean"] = s["mean"]; out["sndbuf_p95"] = s["p95"]; out["sndbuf_max"] = s["max"]
    if rcv_vals:
        s = stats(rcv_vals)
        out["rcvbuf_mean"] = s["mean"]; out["rcvbuf_p95"] = s["p95"]; out["rcvbuf_max"] = s["max"]
    if retrans_per_s_vals:
        s = stats(retrans_per_s_vals)
        out["retrans_per_s_mean"] = s["mean"]; out["retrans_per_s_p95"] = s["p95"]; out["retrans_per_s_max"] = s["max"]

    return out

def write_summary_csv(path: str, agg_rows: List[Dict[str, float]]) -> None:
    df = pd.DataFrame(agg_rows)
    Path(path).parent.mkdir(parents=True, exist_ok=True)
    df.to_csv(path, index=False)


def main():
    ap = argparse.ArgumentParser(description="Analyze MQTT subscriber latency logs")
    ap.add_argument("--mode", choices=["single", "compare"], default="single")
    ap.add_argument("--glob", help="Glob pattern for latency CSVs (single mode)")
    ap.add_argument("--glob-base", help="Glob pattern for baseline latency CSVs (compare mode)")
    ap.add_argument("--glob-ours", help="Glob pattern for ours latency CSVs (compare mode)")
    ap.add_argument("--lat-min", type=float, default=None, help="Drop samples with latency < LAT_MIN (sec)")
    ap.add_argument("--lat-max", type=float, default=None, help="Drop samples with latency > LAT_MAX (sec)")
    ap.add_argument("--eda-base", type=str, default=None, help="Path to baseline eda_log.jsonl (optional)")
    ap.add_argument("--eda-ours", type=str, default=None, help="Path to ours eda_log.jsonl (optional)")
    ap.add_argument("--out", type=str, default=None, help="Output CSV summary path")
    ap.add_argument("--per-host-out", type=str, default=None, help="Output CSV (per-host breakdown)")
    args = ap.parse_args()

    if args.mode == "single":
        if not args.glob:
            ap.error("--glob is required for single mode")
        df = load_glob(args.glob)
        df = clip_latencies(df, args.lat_min, args.lat_max)
        per_host, agg = summarize(df, label="single")
        print("\n=== SINGLE SET SUMMARY ===")
        print(pd.DataFrame([agg]).to_string(index=False, float_format=lambda x: f"{x:,.3f}"))
        if args.per_host_out:
            Path(args.per_host_out).parent.mkdir(parents=True, exist_ok=True)
            per_host.to_csv(args.per_host_out, index=False)
            print(f"[OK] per-host table → {args.per_host_out}")
        if args.out:
            write_summary_csv(args.out, [agg])
            print(f"[OK] summary CSV → {args.out}")

        # Optional EDA (single)
        eda_path = args.eda_base or args.eda_ours
        # SINGLE 모드에서
        eda_summary = load_eda_jsonl(eda_path)
        if eda_summary:
            print("\n--- eBPF EDA (optional) ---")
            for k in ["rtt_ms_mean","rtt_ms_p95","rtt_ms_max",
                    "retrans_per_s_mean","retrans_per_s_p95","retrans_per_s_max",
                    "sndbuf_mean","sndbuf_p95","sndbuf_max",
                    "rcvbuf_mean","rcvbuf_p95","rcvbuf_max"]:
                if k in eda_summary:
                    unit = "ms" if k.startswith("rtt_ms") else ("/s" if "retrans_per_s" in k else "B")
                    print(f"{k:>20}: {eda_summary[k]:,.2f} {unit}")


    else:  # compare
        if not args.glob_base or not args.glob_ours:
            ap.error("--glob-base and --glob-ours are required for compare mode")

        df_base = load_glob(args.glob_base)
        df_ours = load_glob(args.glob_ours)
        df_base = clip_latencies(df_base, args.lat_min, args.lat_max)
        df_ours = clip_latencies(df_ours, args.lat_min, args.lat_max)

        per_host_base, agg_base = summarize(df_base, label="baseline")
        per_host_ours, agg_ours = summarize(df_ours, label="ours")

        # Improvements (%): positive = better (lower latency is better; higher throughput is better)
        def pct_improve(old: float, new: float, lower_is_better: bool = True) -> float:
            if (old is None) or (new is None) or (not math.isfinite(old)) or (old == 0):
                return float("nan")
            if lower_is_better:
                return (old - new) / old * 100.0
            else:
                return (new - old) / old * 100.0

        compare_row = {
            "metric": ["p50_ms","p90_ms","p95_ms","p99_ms","mean_ms","throughput_msg_s"],
            "baseline": [agg_base["p50_ms"], agg_base["p90_ms"], agg_base["p95_ms"], agg_base["p99_ms"], agg_base["mean_ms"], agg_base["throughput_msg_s"]],
            "ours":     [agg_ours["p50_ms"], agg_ours["p90_ms"], agg_ours["p95_ms"], agg_ours["p99_ms"], agg_ours["mean_ms"], agg_ours["throughput_msg_s"]],
            "improve_%":[
                pct_improve(agg_base["p50_ms"], agg_ours["p50_ms"], True),
                pct_improve(agg_base["p90_ms"], agg_ours["p90_ms"], True),
                pct_improve(agg_base["p95_ms"], agg_ours["p95_ms"], True),
                pct_improve(agg_base["p99_ms"], agg_ours["p99_ms"], True),
                pct_improve(agg_base["mean_ms"], agg_ours["mean_ms"], True),
                pct_improve(agg_base["throughput_msg_s"], agg_ours["throughput_msg_s"], False),
            ]
        }
        cmp_df = pd.DataFrame(compare_row)

        print("\n=== COMPARE SUMMARY (baseline vs ours) ===")
        print(pd.DataFrame([agg_base]).to_string(index=False, float_format=lambda x: f"{x:,.3f}"))
        print(pd.DataFrame([agg_ours]).to_string(index=False, float_format=lambda x: f"{x:,.3f}"))
        print("\n--- Improvements (+% means better) ---")
        print(cmp_df.to_string(index=False, float_format=lambda x: f"{x:,.2f}"))

        # Optional: save outputs
        if args.per_host_out:
            # Save both per-host tables with prefixes
            base_out = Path(args.per_host_out)
            ours_out = base_out.with_name(base_out.stem + "_ours.csv")
            base_out.parent.mkdir(parents=True, exist_ok=True)
            per_host_base.to_csv(str(base_out), index=False)
            per_host_ours.to_csv(str(ours_out), index=False)
            print(f"[OK] per-host baseline → {base_out}")
            print(f"[OK] per-host ours     → {ours_out}")

        rows = [agg_base, agg_ours]
        if args.out:
            write_summary_csv(args.out, rows)
            print(f"[OK] summary CSV → {args.out}")

        # Optional EDA summaries
        eda_base = load_eda_jsonl(args.eda_base)
        eda_ours = load_eda_jsonl(args.eda_ours)
        if eda_base or eda_ours:
            print("\n--- eBPF EDA (optional) ---")
            if eda_base:
                print("[baseline]")
                for k, v in eda_base.items():
                    print(f"  {k:>12}: {v:,.2f}")
            if eda_ours:
                print("[ours]")
                for k, v in eda_ours.items():
                    print(f"  {k:>12}: {v:,.2f}")


if __name__ == "__main__":
    main()
